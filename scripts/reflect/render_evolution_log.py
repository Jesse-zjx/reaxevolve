#!/usr/bin/env python3
"""Render EVOLUTION_LOG.md from EVOLUTION_LOG.jsonl.

The human view is generated so it cannot drift from the record, and so the summary reports
what the ledger actually supports rather than a count of entries: how many revisions close
with a measurement, how many of those met their stated expectation, and how many cannot be
closed and why.

  python scripts/reflect/render_evolution_log.py [--check]
"""
from __future__ import annotations

import argparse
import json
import os
from collections import Counter

PKG = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LOG = os.path.join(PKG, "evolution", "EVOLUTION_LOG.jsonl")
OUT = os.path.join(PKG, "evolution", "EVOLUTION_LOG.md")


def render(rows: list[dict]) -> str:
    by_class = Counter(r.get("class") for r in rows)
    by_outcome = Counter(r.get("outcome") or "applied" for r in rows)
    closed = [r for r in rows if r.get("closed_status") == "closed"]
    met = Counter(str(r.get("expectation_met")) for r in closed)
    not_closable = [r for r in rows if r.get("closed_status") == "not_closable"]
    modes = Counter(m for r in rows for m in (r.get("failure_mode") or []))
    final_v: dict[str, int] = {}
    for r in rows:
        if r.get("asset_version_after") is not None and r.get("outcome") != "rolled_back":
            final_v[r["asset_id"]] = r["asset_version_after"]

    L = [
        "# Evolution log",
        "",
        "> Generated by `scripts/reflect/render_evolution_log.py` from `EVOLUTION_LOG.jsonl`.",
        "> Do not hand-edit. Background and field semantics: `evolution/README.md`.",
        "",
        "Revisions are ordered by `seq` and versioned per asset. There are no wall-clock",
        "timestamps: what has to be checkable is the order of revisions, the evidence that",
        "triggered each one, and the pre-change snapshot it can be diffed against.",
        "",
        f"**{len(rows)} revision records** — "
        + ", ".join(f"{k} {v}" for k, v in by_class.most_common())
        + " · "
        + ", ".join(f"{k} {v}" for k, v in by_outcome.most_common()),
        "",
        "## What the ledger supports",
        "",
        f"- **{len(closed)}** revisions have a downstream link: "
        + ", ".join(f"expectation_met={k} ×{v}" for k, v in sorted(met.items())),
        f"- **{len(not_closable)}** cannot be closed. This is not the same as "
        "\"nothing reused them\" — the reason is recorded per record: either no vectored "
        "attempt records that asset, or the campaign stopped before an attempt ran under the "
        "revised version.",
        "",
        "`expectation_met` is **observational**: a balanced window of attempts either side of "
        "the revision, not a replay. The causal arm is the repair/transfer replay, which holds "
        "everything except the asset version fixed. See `evolution/README.md`.",
        "",
        "Only `qm_feedback` revisions carry a claim about capability. `plumbing` fixes a path",
        "or a format; `reorganization` renames or splits the asset surface.",
        "",
        "## Triggering failure modes",
        "",
        "Ids from `policy/failure_modes.md`, the human-set taxonomy.",
        "",
        "| Failure mode | Revisions |",
        "|---|---|",
    ]
    L += [f"| `{k}` | {v} |" for k, v in modes.most_common()]

    L += ["", "## Revisions per asset", "", "| Asset | Revisions | Final version |", "|---|---|---|"]
    for a, n in sorted(Counter(r["asset_id"] for r in rows).items()):
        fv = final_v.get(a)
        L.append(f"| `{a}` | {n} | {'v%d' % fv if fv is not None else '—'} |")

    L += ["", "## Entries", ""]
    for r in rows:
        vb, va = r.get("asset_version_before"), r.get("asset_version_after")
        if r.get("outcome") == "rolled_back":
            ver = f"v{vb} → rolled back"
        elif vb is not None and va is not None:
            ver = f"v{vb}→v{va}"
        else:
            ver = "—"
        tax = r.get("taxonomy_version")
        fm = ",".join(r.get("failure_mode") or []) or "—"
        L.append(f"- `{r.get('seq'):03d}` **{r.get('asset_id')}** {ver} [{r.get('class')}]")
        L.append(f"  - failure mode: `{fm}`" + (f" ({tax})" if tax else ""))
        if r.get("intended_effect"):
            L.append(f"  - intended effect: {r['intended_effect']}")
        if r.get("closed_status") == "closed":
            e = r.get("expectation_evidence") or {}
            rate = ""
            if e.get("rate_before") is not None and e.get("rate_after") is not None:
                rate = (f"; targeted-mode rate {e['rate_before']} → {e['rate_after']} "
                        f"over {e.get('attempts_after')} later attempts")
            L.append(f"  - **expectation met: {r.get('expectation_met')}**{rate}")
            fdu = r.get("first_downstream_use") or {}
            if fdu.get("edge"):
                L.append(f"  - first downstream use: `{fdu['edge']}` ({fdu.get('status')})")
        elif r.get("closed_reason"):
            L.append(f"  - not closable: {r['closed_reason']}")
        if r.get("snapshot"):
            L.append(f"  - snapshot: `{r['snapshot']}`")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the rendered file is stale")
    a = ap.parse_args()
    rows = [json.loads(l) for l in open(LOG) if l.strip()]
    text = render(rows)
    if a.check:
        cur = open(OUT).read() if os.path.isfile(OUT) else ""
        if cur != text:
            print("EVOLUTION_LOG.md is stale — rerun without --check")
            return 1
        print("EVOLUTION_LOG.md matches EVOLUTION_LOG.jsonl")
        return 0
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT, PKG)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
