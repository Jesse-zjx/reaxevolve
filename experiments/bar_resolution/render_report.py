#!/usr/bin/env python3
"""Turn the bar-resolution probe's verdicts into the control writeup.

Reads the verdict records the probe's runs left under `runs/bar_resolution/` and classifies each
against the outcomes declared in `preregistration/bar_resolution_probe.md` before the run. The
classification is mechanical so that it cannot drift toward the expected answer: it reads the
imaginary-mode list and the endpoint-match flags and nothing else.

  python experiments/bar_resolution/render_report.py            # print
  python experiments/bar_resolution/render_report.py --write     # also write RESULT.md
"""
from __future__ import annotations

import argparse
import glob
import json
import os

PKG = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RUNS = os.path.join(PKG, "runs", "bar_resolution")
HERE = os.path.join(PKG, "experiments", "bar_resolution")
# The verdict records, copied out of the run tree. `runs/` is untracked because it carries ORCA
# scratch by the tens of megabytes; these are the few kilobytes the report actually rests on, so a
# reader can check it without re-running two and a half hours of DFT.
VERDICTS = os.path.join(HERE, "verdicts")
OUT = os.path.join(HERE, "RESULT.md")

# The step, and the saddle the campaign deposited for it.
STEP_R = "O=C(CO)C(O)C(O)C(O)CO"
STEP_P = "OCC(O)=C(O)C(O)C(O)CO"
DEPOSITED_IMAG = -2042.5
DEPOSIT = "deposits/glucose_ff_review_v1 step 2"


def classify(v: dict) -> tuple[str, str]:
    """Outcome letter and the reason, from the declared table only."""
    imag = v.get("ts_imag_all") or ([v["ts_imag_cm-1"]] if v.get("ts_imag_cm-1") else [])
    em = v.get("endpoint_match") or {}
    endpoints_ok = (em.get("F_isReactant") and em.get("B_isProduct")) or (
        em.get("F_isProduct") and em.get("B_isReactant")
    )
    if not imag:
        return "C", "no imaginary mode recorded: not a saddle, or the run did not get that far"
    if len(imag) > 1:
        return "A", f"{len(imag)} imaginary modes ({', '.join(str(x) for x in imag)} cm-1)"
    if not endpoints_ok:
        flags = ", ".join(f"{k}={bool(val)}" for k, val in em.items())
        return "A", (
            f"one imaginary mode ({imag[0]} cm-1), so the saddle is clean, but the IRC does not "
            f"connect the stated endpoints ({flags})"
        )
    return "B", f"one imaginary mode ({imag[0]} cm-1) and the IRC connects R and P"


def verdict_files() -> list[str]:
    """Prefer the tracked archive, so the report regenerates in a fresh clone."""
    tracked = sorted(glob.glob(os.path.join(VERDICTS, "*.json")))
    if tracked:
        return tracked
    return sorted(glob.glob(os.path.join(RUNS, "**", "strict_cache.json"), recursive=True))


def collect() -> list[dict]:
    rows = []
    for path in verdict_files():
        for key, v in json.load(open(path)).items():
            letter, why = classify(v)
            rows.append({
                "name": v.get("name"),
                "attempt_dir": os.path.relpath(os.path.dirname(path), PKG),
                "status": v.get("status"),
                "policy_pass": v.get("policy_pass"),
                "imag": v.get("ts_imag_all") or [v.get("ts_imag_cm-1")],
                "endpoint_match": v.get("endpoint_match"),
                "detail": v.get("detail"),
                "outcome": letter,
                "why": why,
                "asset_set": (v.get("asset_versions") or {}).get("asset_set"),
                "fingerprint": v.get("input_fingerprint"),
            })
    return rows


def render(rows: list[dict]) -> str:
    L: list[str] = []
    A = [r for r in rows if r["outcome"] == "A"]
    B = [r for r in rows if r["outcome"] == "B"]
    C = [r for r in rows if r["outcome"] == "C"]
    accepted = [r for r in rows if r["policy_pass"]]

    L.append("# Bar-resolution negative control — result")
    L.append("")
    L.append("Generated by `experiments/bar_resolution/render_report.py` from the verdict records")
    L.append("under `runs/bar_resolution/`. Design and the outcomes declared before the run:")
    L.append("`preregistration/bar_resolution_probe.md`.")
    L.append("")

    if not rows:
        L.append("No verdicts recorded yet.")
        return "\n".join(L) + "\n"

    L.append("## What the control shows")
    L.append("")
    if A and not B and not accepted:
        n = len(rows)
        subject = "the single naive candidate" if n == 1 else f"all {n} naive candidates"
        L.append(f"The bar rejected {subject}. It has resolution on this step: a method that "
                 "should fail did fail.")
    elif B:
        L.append(f"{len(B)} of {len(rows)} candidates met the bar. Uniform interpolation actually "
                 "solved this step, so the control is **inconclusive here** — this is not evidence "
                 "against the bar, and per the preregistration it is reported rather than re-rolled.")
    elif C and not A:
        L.append("No candidate produced a usable saddle, so the control says nothing about the "
                 "bar. Reported as a run failure.")
    L.append("")
    L.append("The sharper reading is in *which* clause did the work. See the table.")
    L.append("")

    L.append("## The probe")
    L.append("")
    L.append(f"- step: `{STEP_R}` → `{STEP_P}` (keto → enol, intramolecular proton transfer)")
    L.append(f"- deposited saddle for this step: {DEPOSITED_IMAG} cm⁻¹, from {DEPOSIT}")
    L.append("- guess method: uniform linear interpolation, `tools/guess/auto_guess.py`, no "
             "reaction-coordinate reasoning")
    L.append("- acceptance path: unmodified `tools/workflow/run_qm_step.py` → "
             "`policy/acceptance/check_strict_bar`")
    L.append(f"- asset set: {rows[0].get('asset_set')}")
    L.append("")

    L.append("## Candidates")
    L.append("")
    L.append("| guess | imaginary modes (cm⁻¹) | IRC connects R and P | verdict | outcome |")
    L.append("|---|---|---|---|---|")
    for r in rows:
        em = r["endpoint_match"] or {}
        ok = (em.get("F_isReactant") and em.get("B_isProduct")) or (
            em.get("F_isProduct") and em.get("B_isReactant")
        )
        imag = ", ".join(str(x) for x in (r["imag"] or []) if x is not None) or "—"
        L.append(f"| `{r['name']}` | {imag} | {'yes' if ok else 'no'} | "
                 f"{r['status']} | {r['outcome']} |")
    L.append("")
    for r in rows:
        L.append(f"- `{r['name']}`: {r['why']}")
    L.append("")

    # The load-bearing observation, stated only when the data supports it.
    single_clean_but_rejected = [
        r for r in rows
        if r["outcome"] == "A" and r["imag"] and len([x for x in r["imag"] if x]) == 1
    ]
    if single_clean_but_rejected:
        L.append("## Which clause carried the weight")
        L.append("")
        L.append(f"{len(single_clean_but_rejected)} of the rejected candidates had **exactly one "
                 "imaginary mode**. They are genuine first-order saddles, just not the ones that "
                 "connect the stated reactant and product — the imaginary frequencies are far from "
                 f"the deposited {DEPOSITED_IMAG} cm⁻¹, and the IRC runs to different structures.")
        L.append("")
        L.append("A bar that asked only \"is this a proper transition state?\" would have accepted "
                 "them. The clause that rejected them is the endpoint criterion: the IRC has to "
                 "relax to the stated neutral reactant and product. That is the clause doing the "
                 "work, and this control is the evidence for it.")
        L.append("")

    L.append("## Limits of this control")
    L.append("")
    L.append("- One step, one guess method. It shows the bar rejects *this* naive method *here*; "
             "it does not bound the false-accept rate in general.")
    L.append("- The step is a proton transfer, the case where uniform interpolation is worst. A "
             "control on a step with a looser reaction coordinate would be a weaker test of the "
             "guess method and a different test of the bar.")
    L.append("- It says nothing about false *rejections*: how often the bar turns away a correct "
             "mechanism is measured by negative control B, not here.")
    L.append("")
    L.append("## Reproducing")
    L.append("")
    L.append("```bash")
    L.append("bash experiments/bar_resolution/run_probe.sh")
    L.append("python experiments/bar_resolution/render_report.py --write")
    L.append("```")
    L.append("")
    L.append("This report is generated from `experiments/bar_resolution/verdicts/`, the verdict "
             "records copied out of the run tree; `runs/` itself is untracked because it carries "
             "ORCA scratch by the tens of megabytes. Input geometry fingerprints:")
    L.append("")
    for r in rows:
        for k, v in (r["fingerprint"] or {}).items():
            L.append(f"- `{r['name']}`: `{k}` → `{v}`")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    rows = collect()
    text = render(rows)
    print(text)
    if a.write:
        with open(OUT, "w") as fh:
            fh.write(text)
        print(f"[wrote] {os.path.relpath(OUT, PKG)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
