#!/usr/bin/env python3
"""Render REPRODUCTION_REPORT.md from the tracked result data, and nothing else.

The original generator read the ORCA scratch directory, so it could not run from a clone —
and a hand-maintained report drifts: the version shipped with the campaign said six steps
closed while the scored data said seven, because a later round recovered one more and the
prose was never updated.

This reads only `comparison.json` (scored, one row per deposit step) and `results/*.json`
(raw per-step outcome), both of which travel with the repository, so the numbers in the
report cannot disagree with the data by construction.

Usage: python experiments/rediscovery/render_report.py [--check]
  --check  exit non-zero if the rendered report differs from the file on disk
"""
from __future__ import annotations

import argparse
import json
import os
import re
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
COMPARISON = os.path.join(HERE, "comparison.json")
REPORT = os.path.join(HERE, "REPRODUCTION_REPORT.md")

ROUTE_DEPOSIT = {
    "HMF": "glucose_hmf_review_v3",
    "HAA": "glucose_haa_review_v1",
    "FF": "glucose_ff_review_v1",
}

# Agreement threshold for "the same saddle". Beyond this the run found a different
# transition state for the same transformation, which is still a valid STRICT step.
SAME_SADDLE_CM = 40.0


def step_index(row) -> int:
    """`step` is a directory name such as `step_1_dehydration`, not a number."""
    m = re.search(r"\d+", str(row.get("step") or row.get("id") or ""))
    return int(m.group()) if m else 0


def load() -> list[dict]:
    rows = json.load(open(COMPARISON))
    return sorted(rows, key=lambda r: (r.get("route") or "", step_index(r)))


def endpoint_tag(e) -> str:
    """The strict endpoint criterion in one field: both raw IRC ends are R and P.

    Which end is which only reflects the sign convention of the IRC run, so either
    orientation counts.
    """
    if not isinstance(e, dict):
        return "—"
    f_r, f_p = bool(e.get("F_isReactant")), bool(e.get("F_isProduct"))
    b_r, b_p = bool(e.get("B_isReactant")), bool(e.get("B_isProduct"))
    if (f_r and b_p) or (f_p and b_r):
        return "R↔P"
    hits = sum((f_r, f_p, b_r, b_p))
    if hits == 0:
        return "neither end"
    return "one end only"


def imag(row, key):
    v = row.get(key)
    if isinstance(v, list):
        v = v[0] if v else None
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def classify(row) -> tuple[str, float | None]:
    """STRICT rows split by whether they landed on the deposited saddle."""
    if row.get("status") != "STRICT":
        return "did_not_close", None
    got, ref = imag(row, "imag_all"), imag(row, "imag_ref")
    if got is None or ref is None:
        return "strict_unknown_saddle", None
    d = abs(got - ref)
    return ("same_saddle" if d <= SAME_SADDLE_CM else "different_saddle"), d


def render(rows) -> str:
    buckets = {}
    deltas = []
    for r in rows:
        cls, d = classify(r)
        buckets.setdefault(cls, []).append(r)
        if cls == "same_saddle" and d is not None:
            deltas.append(d)

    n = len(rows)
    n_strict = sum(1 for r in rows if r.get("status") == "STRICT")
    same = buckets.get("same_saddle", [])
    diff = buckets.get("different_saddle", [])
    missed = buckets.get("did_not_close", [])
    wall = sum(float(r.get("wall") or 0) for r in rows)

    def ids(rs):
        return ", ".join(r["id"] for r in rs) or "—"

    L = [
        "# Re-deriving the delivered routes from SMILES alone",
        "",
        "> Generated by `experiments/rediscovery/render_report.py` from `comparison.json`.",
        "> Do not hand-edit: regenerate instead.",
        "",
        "Every elementary step of the three expert-reviewed deposits "
        + ", ".join(f"`{v}`" for v in ROUTE_DEPOSIT.values())
        + " was rebuilt using the automated dispatcher alone — reactant and product SMILES in,",
        "guess generation, OptTS, NumFreq and IRC out. No geometry, atom index or mechanism was",
        "taken from the deposits. The deposited numbers were used only afterwards, to score the",
        "result.",
        "",
        "This is the hard baseline referenced as negative control B in `evidence/controls.md`:",
        "it measures how far the guessing stack gets when it is refused the answer, not whether",
        "the system works.",
        "",
        "## Result",
        "",
        f"**{n_strict} of the {n} steps closed as STRICT** — one imaginary mode, raw IRC ends",
        "matching the neutral reactant and product exactly.",
        "",
        "| | steps | which |",
        "|---|---|---|",
        f"| recovered the deposited saddle | {len(same)} | {ids(same)} |",
        f"| valid STRICT step, different saddle | {len(diff)} | {ids(diff)} |",
        f"| did not close | {len(missed)} | see the table below |",
        "",
    ]

    if deltas:
        L += [
            f"Where the deposited saddle was recovered, the imaginary frequency agrees to "
            f"**{sum(deltas)/len(deltas):.1f} cm⁻¹ on average and {max(deltas):.1f} cm⁻¹ at worst** "
            f"(same-saddle threshold {SAME_SADDLE_CM:.0f} cm⁻¹).",
            "",
        ]
    if diff:
        L += [
            "The runs that converged on a different saddle for the same transformation missed the",
            "deposited frequency by "
            + ", ".join(
                f"{abs((imag(r,'imag_all') or 0) - (imag(r,'imag_ref') or 0)):.0f}" for r in diff
            )
            + " cm⁻¹, so the two categories are not close to being confusable.",
            "",
        ]

    L += [
        "## Per-step outcome",
        "",
        "| id | route | step | kind | status | endpoint | imag got | imag deposited | wall (s) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        g, ref = imag(r, "imag_all"), imag(r, "imag_ref")
        L.append(
            "| `%s` | %s | %s | %s | %s | %s | %s | %s | %s |"
            % (
                r.get("id"),
                r.get("route"),
                step_index(r),
                r.get("kind") or r.get("dkind") or "—",
                r.get("status"),
                endpoint_tag(r.get("endpoint")),
                f"{g:.1f}" if g is not None else "—",
                f"{ref:.1f}" if ref is not None else "—",
                f"{float(r.get('wall') or 0):.0f}",
            )
        )

    L += [
        "",
        "## Cost",
        "",
        f"Aggregate wall clock across the {n} jobs: **{wall:.3g} s**. At the 4 cores per job used",
        f"for this pass that is of order **{wall * 4 / 3600:.0f} CPU-hours** for the full sweep.",
        "",
        "## Reading discipline",
        "",
        "Cite this as the hardness of the guessing problem under the strict bar, not as a verdict",
        "on the system. The steps that did not close are the cost of refusing deposited geometry;",
        "the steps that did close, and especially the ones that landed on the same saddle, are",
        "what the measurement is for. Do not merge these counts into the accepted-network count in",
        "`evidence/state/NETWORK_STATE.md`: that one counts edges in the network, this one counts",
        "rediscovery attempts against a fixed 20-step target.",
        "",
        "## Status distribution",
        "",
        "```json",
        json.dumps(
            dict(Counter(r.get("status") or "unknown" for r in rows).most_common()), indent=2
        ),
        "```",
    ]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the report on disk is stale")
    a = ap.parse_args()
    text = render(load())
    if a.check:
        current = open(REPORT).read() if os.path.isfile(REPORT) else ""
        if current != text:
            print("REPRODUCTION_REPORT.md is stale — rerun without --check")
            return 1
        print("REPRODUCTION_REPORT.md matches comparison.json")
        return 0
    open(REPORT, "w").write(text)
    print(f"wrote {os.path.relpath(REPORT, os.path.dirname(HERE))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
